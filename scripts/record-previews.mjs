import { spawn, spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const appId = "com.piratefresh.isthistasty2";

export function previewIds(component, mdx) {
  if (!/^[a-z][a-z0-9-]*$/.test(component)) throw new Error("Use a component folder name, such as button.");
  const ids = [...mdx.matchAll(/<Preview example="([a-z0-9-]+)\/([a-z0-9-]+)"/g)]
    .filter((match) => match[1] === component).map((match) => match[2]);
  if (!ids.length) throw new Error(`No documented examples for ${component}.`);
  return [...new Set(ids)];
}

function run(command, args) {
  const result = spawnSync(command, args, { stdio: "inherit", cwd: root });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} exited with ${result.status}.`);
}

function recording(command, args, stopAfter) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: "inherit", cwd: root });
    const timer = stopAfter ? setTimeout(() => child.kill("SIGINT"), stopAfter) : undefined;
    child.on("error", (error) => { clearTimeout(timer); reject(error); });
    child.on("exit", (code, signal) => {
      clearTimeout(timer);
      if (code === 0 || (stopAfter && signal === "SIGINT")) resolve();
      else reject(new Error(`${command} recording failed (${code ?? signal}).`));
    });
  });
}

async function main() {
  const [component, platform] = process.argv.slice(2);
  const flowsOnly = platform === "--flows-only";
  // Validate before joining a user-supplied component into a path.
  if (!component || !/^[a-z][a-z0-9-]*$/.test(component)) throw new Error("Usage: pnpm previews:record <component> <ios|android|--flows-only>");
  if (!flowsOnly && platform !== "ios" && platform !== "android") throw new Error("Choose ios or android.");
  if (platform === "ios" && process.platform !== "darwin") throw new Error("iOS recording needs macOS and a booted Xcode simulator.");
  const mdx = await readFile(path.join(root, "packages/ui/src", component, "docs.mdx"), "utf8");
  const ids = previewIds(component, mdx);
  const flows = path.join(root, "apps/mobile/.maestro/native/previews", component);
  await mkdir(flows, { recursive: true });

  for (const id of ids) {
    await writeFile(path.join(flows, `${id}.yaml`),
      `# Generated by pnpm previews:record ${component} --flows-only\nappId: ${appId}\n---\n- openLink: isthistasty2://preview/${component}/${id}\n- extendedWaitUntil:\n    visible:\n      id: preview-${component}-${id}\n    timeout: 30000\n- waitForAnimationToEnd\n`);
  }
  await writeFile(path.join(flows, "all.yaml"), `appId: ${appId}\n---\n${ids.map((id) => `- runFlow: ${id}.yaml`).join("\n")}\n`);
  if (flowsOnly) { console.log(`Generated ${ids.length} flows in ${flows}`); return; }

  const output = path.join(root, "apps/docs/public/previews", component);
  await mkdir(output, { recursive: true });
  // Preflight before opening the app or starting device capture.
  run("maestro", ["--version"]);
  run("ffmpeg", ["-version"]);
  run(platform === "ios" ? "xcrun" : "adb", platform === "ios" ? ["simctl", "list", "devices", "booted"] : ["get-state"]);

  for (const id of ids) {
    const raw = path.join(output, `${id}.${platform}.raw.mp4`);
    run("maestro", ["test", path.join(flows, `${id}.yaml`)]);
    if (platform === "ios") {
      await recording("xcrun", ["simctl", "io", "booted", "recordVideo", "--codec=h264", "--force", raw], 6500);
    } else {
      const remote = `/sdcard/tasty-preview-${component}-${id}.mp4`;
      await recording("adb", ["shell", "screenrecord", "--time-limit", "6", remote]);
      run("adb", ["pull", remote, raw]);
      run("adb", ["shell", "rm", remote]);
    }
    run("ffmpeg", ["-y", "-ss", "0.5", "-i", raw, "-t", "5", "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-movflags", "+faststart", path.join(output, `${id}.${platform}.mp4`)]);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
